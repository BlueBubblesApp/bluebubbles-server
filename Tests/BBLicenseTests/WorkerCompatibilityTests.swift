//  WorkerCompatibilityTests
//  That a token minted by the issuing Worker verifies here.
//
//  The Worker is JavaScript and this is Swift, and they agree on four things by convention
//  alone: base64url with the padding stripped, a signature covering `header.claims` rather
//  than the whole token, raw 32-byte keys rather than either language's DER wrapper, and the
//  claim spellings. Every one of them is SILENT when wrong — the token looks well-formed and
//  simply fails to verify — and the first person to find out would be a customer who had
//  just paid.
//
//  The fixture is generated by `Tools/license-worker/selftest.mjs`, which mints through the
//  same code path the Worker uses, including the PKCS8 re-wrap of the raw seed. Regenerate it
//  with that script if the token format ever changes; it carries no real key and no real
//  customer.

import BBCore
import Foundation
import Testing

@testable import BBLicense

@Suite("Worker compatibility")
struct WorkerCompatibilityTests {

  /// Minted by `selftest.mjs`. A throwaway keypair: the private half was never written down.
  static let publicKey =
    "p/xdiD1vEtDD8o2EpqkMYTtM7SrTIOXVjW0SqMBVYfQ="
  static let token =
    "eyJhbGciOiJFZERTQSIsInR5cCI6IkpXVCJ9.eyJ2IjoxLCJzdWIiOiJsa19zZWxmdGVzdCIsInRpZXIiOiJwcm8iLCJyYW5rIjoxLCJmZWF0cyI6W10sIm1hY2hpbmUiOiJjNGIwOTFkMzNiNjEzMzg5YzhlMjY4NDI1Y2UwZjZmZDYyNWMyZmRiZjgyZGEzNzJkNjE3MzNjZGM1NWU5ZjUxIiwiaWF0IjoxNzg5NjA3NjI2LCJleHAiOjE3OTAyMTI0MjYsInN1Yl9lbmQiOjE3OTIxOTk2MjYsImp0aSI6IjJjZjVjZmViLWQ4OTQtNDk3ZC04NGI5LTZiM2ExNWYxZThmOCJ9.DOljTKh4k8YiQqLt1b_d-AIoIRo_7XCYeJ40D1V2fMrZSNio3toOJ1jny3IaO1vWkrgCSKemUJoCXZm-XhFvBw"
  static let machine =
    "c4b091d33b613389c8e268425ce0f6fd625c2fdbf82da372d61733cdc55e9f51"

  @Test("A token minted by the Worker verifies with the embedded key")
  func crossLanguage() throws {
    let key = try LicensePublicKey.parse(base64: Self.publicKey)
    let decoded = try TokenVerifier.verify(Self.token, publicKey: key)

    #expect(decoded.version == 1)
    #expect(decoded.tier == .pro)
    #expect(decoded.tier.rank == 1)
    #expect(decoded.machine == Self.machine)
    #expect(decoded.subject.hasPrefix("lk_"))
    // Present and in the future: a subscription, not a perpetual license.
    #expect(decoded.isPerpetual == false)
    #expect(decoded.expiresAt > decoded.issuedAt)
  }

  /// The signature must cover the claims, not just the header. A verifier that signed only
  /// the header would pass every test above and accept any claims at all.
  @Test("Altering a claim invalidates the Worker's signature")
  func tamperingIsCaught() throws {
    let key = try LicensePublicKey.parse(base64: Self.publicKey)
    var segments = Self.token.split(separator: ".").map(String.init)
    let forged = try JSONSerialization.data(
      withJSONObject: [
        "v": 1, "sub": "lk_x", "tier": "pro", "rank": 99, "feats": [],
        "machine": Self.machine, "iat": 0, "exp": 9_999_999_999, "jti": "x",
      ])
    segments[1] = Base64URL.encode(forged)
    #expect(throws: TokenVerificationError.badSignature) {
      try TokenVerifier.verify(segments.joined(separator: "."), publicKey: key)
    }
  }
}
